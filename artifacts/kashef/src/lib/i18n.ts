const TRANSLATIONS = { ...ENGLISH, ...MORE_ENGLISH };

function readSavedLanguage(): Language {
  if (typeof window === 'undefined') return 'ar';
  try {
    return window.localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'ar';
  } catch {
    return 'ar';
  }
}

let currentLanguage = readSavedLanguage();
const listeners = new Set<() => void>();

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function getSnapshot() {
  return currentLanguage;
}

export function getLanguage(): Language {
  return currentLanguage;
}

export function setLanguage(next: Language): void {
  if (next === currentLanguage) return;
  currentLanguage = next;
  try {
    window.localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Language changes still work for this session when browser storage is blocked.
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = next;
    document.documentElement.dir = next === 'ar' ? 'rtl' : 'ltr';
  }
  listeners.forEach((listener) => listener());
}

export function useLanguage() {
  const language = useSyncExternalStore(subscribe, getSnapshot, () => 'ar');
  return { language, isArabic: language === 'ar', setLanguage };
}

export function t(arabic: string, english?: string): string {
  if (currentLanguage === 'ar') return arabic;
  return english ?? TRANSLATIONS[arabic] ?? arabic;
}

const TEXT_ATTRIBUTES = ['aria-label', 'placeholder', 'title', 'alt'] as const;

function translateTree(node: ReactNode): ReactNode {
  if (typeof node === 'string') {
    const trimmed = node.trim();
    if (!trimmed) return node;
    return node.replace(trimmed, t(trimmed));
  }
  if (Array.isArray(node)) return node.map(translateTree);
  if (!isValidElement<{ children?: ReactNode; 'data-no-translate'?: boolean }>(node)) return node;
  if (node.props['data-no-translate']) return node;
  const translatedAttributes: Record<string, string> = {};
  for (const attribute of TEXT_ATTRIBUTES) {
    const value = node.props[attribute as keyof typeof node.props];
    if (typeof value === 'string') translatedAttributes[attribute] = t(value);
  }
  return cloneElement(node, translatedAttributes, translateTree(node.props.children));
}

/** Translate fixed text in legacy screens without touching user-entered content. */
export function LocalizedContent({ children }: { children: ReactNode }) {
  return createElement(Fragment, null, translateTree(children));
}
